    private void jTipoEnvioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTipoEnvioActionPerformed
        // TODO add your handling code here:
        
        String tipoEnvio = jTipoEnvio.getSelectedItem().toString();
        if (tipoEnvio.equalsIgnoreCase("Envio en bicicleta")) {
            //crear prestamo 
            jLabel4.setVisible(true);
            jLabel3.setVisible(false);
            jLabel2.setVisible(false);
            jTipoEnvio.setVisible(true);    
            jDistanceKm.setVisible(true);
            jChargePerItem.setVisible(false);
               jItems.setVisible(false);
        } else if (tipoEnvio.equalsIgnoreCase("Envio en furgoneta")) {
            // crear objeto saving
          jLabel4.setVisible(true);
            jLabel3.setVisible(false);
            jLabel2.setVisible(false);
            jTipoEnvio.setVisible(true);                
            jDistanceKm.setVisible(true);
             jChargePerItem.setVisible(false);
               jItems.setVisible(false);
        } else if (tipoEnvio.equalsIgnoreCase("Empaque")) {
            //Crear objetos cheques
          jLabel4.setVisible(false);
            jLabel3.setVisible(true);
            jLabel2.setVisible(true);
            jTipoEnvio.setVisible(true); 
            jDistanceKm.setVisible(false);
             jChargePerItem.setVisible(true);
             jItems.setVisible(true);
        }
        
        
        
        
    }//GEN-LAST:event_jTipoEnvioActionPerformed

